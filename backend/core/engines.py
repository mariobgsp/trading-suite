class StochasticEngine(BaseEngine):
    """
    Priority 3 Engine: Stochastic Crossover
    Triggers when Fast %K crosses above %D from below in oversold territory, with volume > SMA 20.
    """
    name = "stochastic_cross"
    priority = 3
    
    def scan(self, df: pd.DataFrame, ticker: str, regime: RegimeSnapshot, profile: "StockProfile | None" = None) -> EntrySignal | None:
        if not regime.allows_engine(self.name):
            return None
            
        if len(df) < 20:
            return None
            
        # Get Stochastic %K and %D
        k_series, d_series = stochastic_oscillator(df, k_period=14, d_period=3)
        
        k_today = k_series.iloc[-1]
        k_yest = k_series.iloc[-2]
        d_today = d_series.iloc[-1]
        d_yest = d_series.iloc[-2]
        
        # Check Cross above: K was below D yesterday, K is above D today
        cross_above = k_yest <= d_yest and k_today > d_today
        
        # Check Oversold (e.g. K < 20 at time of cross)
        is_oversold = k_today < 20.0
        
        # Volume filter
        vol_sma20 = sma(df["Volume"], 20).iloc[-1]
        vol_today = df["Volume"].iloc[-1]
        vol_confirmed = vol_today > vol_sma20
        
        if cross_above and is_oversold and vol_confirmed:
            return EntrySignal(
                engine=self.name,
                ticker=ticker,
                price=float(df["Close"].iloc[-1]),
                score=self.priority * 1.5,
                priority=self.priority,
                details={"k": round(k_today, 2), "d": round(d_today, 2)}
            )
            
        return None

class MACDEngine(BaseEngine):
    """
    Priority 2 Engine: MACD Crossover
    Triggers when MACD line crosses above Signal line, with volume > SMA 20.
    """
    name = "macd_cross"
    priority = 2
    
    def scan(self, df: pd.DataFrame, ticker: str, regime: RegimeSnapshot, profile: "StockProfile | None" = None) -> EntrySignal | None:
        if not regime.allows_engine(self.name):
            return None
            
        if len(df) < 35:
            return None
            
        macd_line, signal_line, _ = macd(df, fast=12, slow=26, signal=9)
        
        macd_today = macd_line.iloc[-1]
        macd_yest = macd_line.iloc[-2]
        sig_today = signal_line.iloc[-1]
        sig_yest = signal_line.iloc[-2]
        
        # Check Cross above: MACD was below Signal yesterday, MACD is above Signal today
        cross_above = macd_yest <= sig_yest and macd_today > sig_today
        
        # Optional: ensure it's crossing upward from below zero (or just any cross)
        # We will use any cross above for now.
        
        # Volume filter
        vol_sma20 = sma(df["Volume"], 20).iloc[-1]
        vol_today = df["Volume"].iloc[-1]
        vol_confirmed = vol_today > vol_sma20
        
        if cross_above and vol_confirmed:
            return EntrySignal(
                engine=self.name,
                ticker=ticker,
                price=float(df["Close"].iloc[-1]),
                score=self.priority * 1.5,
                priority=self.priority,
                details={"macd": round(macd_today, 3), "signal": round(sig_today, 3)}
            )
            
        return None

class MACrossingEngine(BaseEngine):
    """
    Priority 1 Engine: MA Crossover
    Triggers when Fast SMA crosses above Slow SMA (e.g. SMA 50 crosses above SMA 200).
    Requires volume > SMA 20.
    """
    name = "ma_cross"
    priority = 1
    
    def scan(self, df: pd.DataFrame, ticker: str, regime: RegimeSnapshot, profile: "StockProfile | None" = None) -> EntrySignal | None:
        if not regime.allows_engine(self.name):
            return None
            
        if len(df) < 200:
            return None
            
        fast_sma = sma(df["Close"], period=50)
        slow_sma = sma(df["Close"], period=200)
        
        fast_today = fast_sma.iloc[-1]
        fast_yest = fast_sma.iloc[-2]
        slow_today = slow_sma.iloc[-1]
        slow_yest = slow_sma.iloc[-2]
        
        # Check Cross above: Fast was below Slow yesterday, Fast is above Slow today
        cross_above = fast_yest <= slow_yest and fast_today > slow_today
        
        # Volume filter
        vol_sma20 = sma(df["Volume"], 20).iloc[-1]
        vol_today = df["Volume"].iloc[-1]
        vol_confirmed = vol_today > vol_sma20
        
        if cross_above and vol_confirmed:
            return EntrySignal(
                engine=self.name,
                ticker=ticker,
                price=float(df["Close"].iloc[-1]),
                score=self.priority * 1.5,
                priority=self.priority,
                details={"fast_sma": round(fast_today, 2), "slow_sma": round(slow_today, 2)}
            )
            
        return None


