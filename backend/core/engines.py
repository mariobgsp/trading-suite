class DowntrendBounceEngine(BaseEngine):
    """
    Downtrend Bounce Entry Engine.

    Specifically designed to trade DURING downtrends and BEAR regimes
    by identifying high-probability short-term bounce setups. This is
    a momentum mean-reversion hybrid engine.

    Unlike other engines that require uptrend alignment, this engine
    deliberately targets stocks in a downtrend that show signs of a
    short-term capitulation exhaustion and relief bounce.

    Conditions:
    1. Stock is in a downtrend: price < SMA(200) but NOT more than
       DOWNTREND_BOUNCE_MAX_BELOW_SMA200_PCT below it (e.g. 30%)
       — avoids truly broken/delisted candidates.
    2. RSI(14) was recently oversold: previous RSI < 30 (heavy selling)
    3. RSI(14) is now crossing above DOWNTREND_BOUNCE_RSI_MIN from below
       — momentum shift after capitulation.
    4. Today's candle is bullish: close > open AND body > 0.5%
    5. Volume confirmation: > DOWNTREND_BOUNCE_MIN_VOL_RATIO of 20-day average
    6. Close > previous close (buyers gaining control)

    Target: Short-term 3-7 day bounce. Use tight stops (1x ATR)
    and take profit at 2x ATR.

    Priority: 2
    Allowed regimes: BEAR, CAUTION (primary downtrend engine)
    """

    name = "downtrend_bounce"
    priority = 2

    def scan(
        self,
        df: pd.DataFrame,
        ticker: str,
        regime: RegimeSnapshot,
        profile: "StockProfile | None" = None,
    ) -> EntrySignal | None:
        if not regime.allows_engine(self.name):
            return None

        if len(df) < max(200 + 5, 30):
            return None

        last = df.iloc[-1]
        prev = df.iloc[-2]
        last_close = float(last["Close"])
        last_open = float(last["Open"])
        prev_close = float(prev["Close"])

        # 1. Must be in a downtrend (below SMA200) but not completely broken
        from core.indicators import sma as _sma
        sma200 = _sma(df["Close"], 200)
        sma200_val = float(sma200.iloc[-1]) if not pd.isna(sma200.iloc[-1]) else last_close

        if last_close >= sma200_val:
            # If above SMA200, this engine is not for uptrend stocks
            # (other engines handle that)
            return None

        pct_below_sma200 = ((sma200_val - last_close) / sma200_val) * 100
        if pct_below_sma200 > DOWNTREND_BOUNCE_MAX_BELOW_SMA200_PCT:
            # Too far below — likely broken/delisted
            return None

        # 2. & 3. RSI oversold recovery: RSI was < 30 yesterday, now crossing above threshold
        rsi_series = rsi(df["Close"], period=14)
        last_rsi = float(rsi_series.iloc[-1]) if not pd.isna(rsi_series.iloc[-1]) else 50.0
        prev_rsi = float(rsi_series.iloc[-2]) if not pd.isna(rsi_series.iloc[-2]) else 50.0

        rsi_threshold = profile.rsi_oversold + 5.0 if profile else DOWNTREND_BOUNCE_RSI_MIN
        rsi_max = DOWNTREND_BOUNCE_RSI_MAX

        # Must have been oversold before
        if prev_rsi >= 35.0:
            return None

        # Must now be recovering into the bounce RSI band (not already overbought)
        if not (DOWNTREND_BOUNCE_RSI_MIN <= last_rsi <= rsi_max):
            # Also allow if RSI just crossed above oversold threshold
            if not (prev_rsi < rsi_threshold and last_rsi >= rsi_threshold):
                return None

        # 4. Bullish candle: close > open AND body > minimum size
        body_pct = abs(last_close - last_open) / last_close * 100.0
        if last_close <= last_open:
            return None
        if body_pct < DOWNTREND_BOUNCE_MIN_BODY_PCT:
            return None

        # 5. Volume confirmation
        vol_ratio_series = volume_ratio(df, period=20)
        last_vol_ratio = float(vol_ratio_series.iloc[-1]) if not pd.isna(vol_ratio_series.iloc[-1]) else 1.0

        min_vol = profile.volume_spike_threshold * 0.5 if profile else DOWNTREND_BOUNCE_MIN_VOL_RATIO
        if last_vol_ratio < min_vol:
            return None

        # 6. Higher close: buyers gaining control
        if last_close <= prev_close:
            return None

        # Signal confirmed — downtrend bounce setup
        atr_series = atr(df, period=ATR_PERIOD)
        last_atr = float(atr_series.iloc[-1]) if not pd.isna(atr_series.iloc[-1]) else 0.0

        score = self.priority * last_vol_ratio

        return EntrySignal(
            engine=self.name,
            ticker=ticker,
            price=round(last_close, 2),
            score=round(score, 2),
            priority=self.priority,
            details={
                "pct_below_sma200": round(pct_below_sma200, 2),
                "sma200": round(sma200_val, 2),
                "prev_rsi": round(prev_rsi, 2),
                "current_rsi": round(last_rsi, 2),
                "body_pct": round(body_pct, 2),
                "volume_ratio": round(last_vol_ratio, 2),
                "atr": round(last_atr, 2),
                "trade_type": "downtrend_bounce",
                "target_hold_days": "3-7",
            },
        )


# ─── Momentum Confluence Engine ──────────────────────────────────────────────


class MomentumConfluenceEngine(BaseEngine):
    """
    **Momentum Confluence Engine** — The core trading strategy.

    Detects the "perfect momentum" by requiring MULTIPLE independent
    technical indicators to align simultaneously (confluence). Only fires
    when 6+ out of 10 conditions are True, dramatically raising the
    probability of a successful trade.

    Indicators evaluated:
      1. RSI(14) in momentum zone (40-70) and rising
      2. MACD histogram positive and accelerating
      3. MACD line above signal line
      4. Stochastic %K > %D with bullish momentum
      5. Volume > 150% of 20-day average (institutional)
      6. Triple EMA alignment: EMA(9) > EMA(21) > EMA(50), price above all
      7. ADX > 20 with +DI > -DI (confirmed trend strength)
      8. Price Action: bullish candle or higher closes above EMA
      9. OBV slope positive (money flowing in / accumulation)
     10. Williams %R crossing out of oversold or in bullish zone

    The key philosophy: any single indicator can give false signals.
    But when 6-10 indicators agree simultaneously, the probability
    of a genuine momentum breakout is significantly higher.

    Priority: 3 (highest) — Trades in BULL and CAUTION regimes.
    """

    name = "momentum_confluence"
    priority = 3
    allowed_regimes = {"BULL", "CAUTION"}

    def scan(
        self,
        df: pd.DataFrame,
        ticker: str,
        regime: RegimeSnapshot,
        profile: "StockProfile | None" = None,
    ) -> EntrySignal | None:
        """Check for momentum confluence signal."""
        # Regime gate
        if regime.regime.value not in self.allowed_regimes:
            return None

        # Minimum data requirement
        if len(df) < 70:
            return None

        # Import the confluence scorer
        from core.indicators import (
            momentum_confluence_score,
            atr as atr_func,
            is_bullish_engulfing,
            is_hammer,
            vwap_deviation,
        )
        from config.settings import (
            MOMENTUM_MIN_CONFLUENCE,
            MOMENTUM_VOLUME_SURGE_RATIO,
        )

        # ── Compute confluence ────────────────────────────────────────
        confluence = momentum_confluence_score(df)
        count = confluence["confluence_count"]
        score = confluence["score"]

        # Minimum confluence threshold
        if count < MOMENTUM_MIN_CONFLUENCE:
            return None

        # ── Bonus: Candlestick patterns add to confidence ─────────────
        has_engulfing = is_bullish_engulfing(df)
        has_hammer = is_hammer(df)
        candlestick_bonus = 0.5 if has_engulfing else (0.3 if has_hammer else 0.0)

        # ── VWAP confirmation (bonus, not required) ───────────────────
        vwap_dev = vwap_deviation(df, period=20)
        vwap_bonus = 0.3 if vwap_dev > 0 else 0.0

        # ── Adaptive threshold adjustments ────────────────────────────
        if profile is not None:
            # Use per-stock RSI thresholds
            rsi_val = confluence["indicators"].get("rsi", 50)
            if rsi_val < profile.rsi_oversold:
                # Too oversold for momentum, skip (this is a BOW territory)
                return None

        # ── ATR for risk calculations ─────────────────────────────────
        atr_series = atr_func(df, period=ATR_PERIOD)
        last_atr = float(atr_series.iloc[-1]) if not pd.isna(atr_series.iloc[-1]) else 0.0
        if last_atr <= 0:
            return None

        last_close = float(df["Close"].iloc[-1])
        vol_ratio_val = confluence["indicators"].get("volume_ratio", 1.0)

        # ── Score calculation ─────────────────────────────────────────
        # Priority × (weighted_score / max_possible_score) × volume_ratio
        max_score = 11.0  # Sum of all weights
        normalized_score = (score + candlestick_bonus + vwap_bonus) / max_score
        final_score = self.priority * normalized_score * min(vol_ratio_val, 3.0)

        # Regime multiplier: CAUTION regime reduces score
        if regime.regime.value == "CAUTION":
            final_score *= 0.75

        # ── Build detailed signal ─────────────────────────────────────
        conditions_met = [
            k for k, v in confluence["conditions"].items() if v
        ]
        conditions_missed = [
            k for k, v in confluence["conditions"].items() if not v
        ]

        return EntrySignal(
            engine=self.name,
            ticker=ticker,
            price=round(last_close, 2),
            score=round(final_score, 2),
            priority=self.priority,
            details={
                "confluence_count": count,
                "confluence_score": score,
                "conditions_met": conditions_met,
                "conditions_missed": conditions_missed,
                "rsi": confluence["indicators"].get("rsi", 0),
                "macd_histogram": confluence["indicators"].get("macd_histogram", 0),
                "stoch_k": confluence["indicators"].get("stoch_k", 0),
                "stoch_d": confluence["indicators"].get("stoch_d", 0),
                "adx": confluence["indicators"].get("adx", 0),
                "plus_di": confluence["indicators"].get("plus_di", 0),
                "minus_di": confluence["indicators"].get("minus_di", 0),
                "williams_r": confluence["indicators"].get("williams_r", 0),
                "obv_slope": confluence["indicators"].get("obv_slope", 0),
                "volume_ratio": vol_ratio_val,
                "ema9": confluence["indicators"].get("ema9", 0),
                "ema21": confluence["indicators"].get("ema21", 0),
                "ema50": confluence["indicators"].get("ema50", 0),
                "has_engulfing": has_engulfing,
                "has_hammer": has_hammer,
                "vwap_deviation_pct": round(vwap_dev, 2),
                "atr": round(last_atr, 2),
                "trade_type": "momentum_confluence",
            },
        )


